/// The focus region as a number, whichever type `HudNav::focus` has: `i32` today, `GroupId` after
/// the split. The two spell the same three places (scrubber 0, control row 1, tabs 2).
trait Region {
    fn region(&self) -> u32;
}
impl Region for i32 {
    fn region(&self) -> u32 {
        *self as u32
    }
}
impl Region for GroupId {
    fn region(&self) -> u32 {
        self.0
    }
}

/// Who occupies the control row, built only through the public constructors.
#[derive(Clone, Copy, Debug)]
enum Occupant {
    /// the ordinary Subtitles, Audio and More discs (a film)
    Plain,
    /// an episode with a neighbour on both sides: Previous and Next join the row
    Episode,
    /// the first episode of a show: only Next joins
    NextOnly,
    /// the last episode of a show: only Previous joins
    PreviousOnly,
    /// a Skip Intro pill
    SkipIntro,
    /// a Skip Credits pill (a credits segment that does not run to the end)
    SkipCredits,
    /// Watch Credits + Next Episode
    UpNext,
}

fn marker(kind: plx_data::metadata::MarkerKind, final_seg: bool) -> plx_data::metadata::Marker {
    plx_data::metadata::Marker { kind, start_ms: 10_000, end_ms: 40_000, final_seg }
}

fn slot_of(occupant: Occupant) -> ControlSlot {
    use plx_data::metadata::MarkerKind::{Credits, Intro};
    use plx_media::route::NextEpisodeMode::Countdown;
    let discs = |previous, next| ControlSlot::Discs(Controls { previous, next, restart: false });
    let slot = match occupant {
        Occupant::Plain => ControlSlot::Discs(Controls::NONE),
        Occupant::Episode => discs(true, true),
        Occupant::NextOnly => discs(false, true),
        Occupant::PreviousOnly => discs(true, false),
        Occupant::SkipIntro => slot_for(Some(marker(Intro, false)), false, Countdown),
        Occupant::SkipCredits => slot_for(Some(marker(Credits, false)), false, Countdown),
        Occupant::UpNext => slot_for(Some(marker(Credits, true)), true, Countdown),
    };
    // the constructors above are the claim; check the variant each one built
    let built = match occupant {
        Occupant::Plain | Occupant::Episode | Occupant::NextOnly | Occupant::PreviousOnly => {
            matches!(slot, ControlSlot::Discs(_))
        }
        Occupant::SkipIntro | Occupant::SkipCredits => matches!(slot, ControlSlot::Skip(_)),
        Occupant::UpNext => matches!(slot, ControlSlot::UpNext(_)),
    };
    assert!(built, "{occupant:?} built the wrong occupant");
    slot
}

/// The idle playhead every pin assumes. Reading these is how the pins hold the premise: another
/// module that leaked a duration, a pause or a busy pipeline would otherwise surface as a
/// mismatching table row that looks like a behaviour change.
fn assert_idle_playhead() {
    use std::sync::atomic::Ordering::Relaxed;
    assert_eq!(plx_media::player::SHARED.duration_ns.load(Relaxed), 0, "a leaked duration");
    assert!(!plx_media::player::TX.paused.load(Relaxed), "a leaked pause");
    let ps = plx_media::route::idle_session_for_test();
    assert!(!plx_media::player::loading(ps), "a busy pipeline");
    assert_ne!(
        plx_media::route::instant_dpad_seeking(),
        plx_plex::plex::session::InstantDpadSeeking::On,
        "instant D-pad seeking changes what LEFT and RIGHT do on a hidden transport",
    );
}

/// Mounts the player screen for the one page the dispatcher opens.
struct PinMounter;
impl Mounter<TestHost> for PinMounter {
    fn mount(
        &mut self,
        _id: InstanceId,
        _arg: &FixtureArg,
        _ret: &ReturnState<u32, PageMemory>,
        cx: &Cx<'_, TestHost>,
        _fx: &mut Effects<'_, TestHost>,
    ) -> Box<dyn Screen<TestHost>> {
        let InputOwner::Entry(entry) = cx.owner else { panic!("the page owns its own input") };
        Box::new(PlayerScreen::new(entry))
    }
}

/// The application's side of the frame, reduced to recording what the player asked for.
