/// Modern retains the full control family. Classic intentionally hides ordinary discs and
/// all tabs, but keeps contextual Skip/Up Next. Both modes expose only clickable drawn stops;
/// the historical numeric geometry above remains an independent characterization.
#[test]
fn current_modes_keep_the_censused_controls_and_presented_hits() {
    use plx_appkit::player_hud::{ELEM_SCRUB, row_index};
    use plx_ui::hit::{HitMap, PointerKind};
    use plx_ui::screen::DrawFrame;
    let _g = plx_base::testlock::serial();
    assert_idle_playhead();
    for case in CENSUSES {
        let _chapters = case.chapters.then(Chaptered::install);
        for mode in [UiMode::Classic, UiMode::Modern] {
            let cx = census_cx(mode);
            let mut screen = census_screen(case.occupant, case.failed);
            // A known duration is part of the presented frame, not an inferred decoder global.
            screen.model.duration_ns = 100_000_000_000;
            let geometry = screen.hud_geometry(&cx);
            let mut groups = Vec::new();
            Focusable::<CensusHost>::groups(&screen, &cx, &mut groups);
            let classic = mode == UiMode::Classic;
            let contextual = matches!(case.occupant,
                Occupant::SkipIntro | Occupant::SkipCredits | Occupant::UpNext);
            // This is the product contract, independent of the layout/visibility helpers
            // under test. In Classic even absent contextual item IDs have no focus group.
            let expected = |group: Option<u32>, present: bool| match group {
                Some(2) if classic => (None, false),
                Some(1) if classic && (!contextual || !present) => (None, false),
                _ => (group, present),
            };
            assert_eq!(groups.iter().map(|g| (g.id.0, g.len)).collect::<Vec<_>>(),
                case.groups.iter().filter(|g| !classic || (g.0 != 2 && (g.0 != 1 || contextual)))
                    .map(|g| (g.0, g.1)).collect::<Vec<_>>(), "{} {mode:?}", case.name);
            for &(elem, group, rect) in case.places {
                let (expected_group, expected_place) = expected(group, rect.is_some());
                assert_eq!(Focusable::<CensusHost>::group_of(&screen, &elem, &cx).map(|g| g.0),
                    expected_group, "{} {mode:?} {elem}: focus eligibility", case.name);
                let placed = Focusable::<CensusHost>::place(&screen, &elem, &cx, At::Drawn);
                assert_eq!(placed.is_some(), expected_place, "{} {mode:?} {elem}", case.name);
                if let Some(placed) = placed {
                    assert_eq!(placed.rest_rect, placed.rect);
                    assert_eq!(placed.index, None);
                    let clip = if mode == UiMode::Modern && matches!(screen.slot, ControlSlot::Discs(_))
                        && row_index(elem).is_some() { geometry.row } else { plx_ui::Rect::FULL };
                    assert_eq!(placed.clip, clip, "{} {mode:?} {elem}", case.name);
                }
            }
            let mut frame = DrawFrame::new(&cx, plx_ui::Painter::root());
            screen.record_stops(&mut frame, true);
            let stops = frame.into_stops();
            let expected_stops: Vec<_> = case.places.iter().filter_map(|&(elem, group, rect)| {
                let (group, present) = expected(group, rect.is_some());
                (present && if case.failed { group == Some(3) } else { matches!(group, Some(0..=2)) })
                    .then_some(elem)
            }).collect();
            assert_eq!(stops.iter().map(|s| s.key.elem).collect::<Vec<_>>(), expected_stops,
                "{} {mode:?}: only drawn controls are registered", case.name);
            let mut map = HitMap::new();
            map.fill(stops.clone());
            map.swap();
            for stop in stops {
                let placed = Focusable::<CensusHost>::place(&screen, &stop.key.elem, &cx, At::Drawn).unwrap();
                assert_eq!(stop.rect, placed.rect);
                // DrawFrame intersects the root clip: f32 (y + h) - y can round h.
                // Reuse the census's 0.001 px bound only for that normalized clip.
                assert!(near(ext(stop.clip), ext(placed.clip)),
                    "{} {mode:?}: control {} clip {:?} differs from {:?}",
                    case.name, stop.key.elem, stop.clip, placed.clip);
                let (x, y) = if stop.key.elem == ELEM_SCRUB {
                    (geometry.playbar.cx(), geometry.playbar.cy())
                } else { (stop.rect.cx(), stop.rect.cy()) };
                assert!(stop.rect.contains(x, y) && stop.clip.contains(x, y));
                let hit = map.resolve(Some(ENTRY), PointerKind::Click, x, y, None);
                assert_eq!(hit.activate.map(|(key, _)| key.elem), Some(stop.key.elem),
                    "{} {mode:?}: presented control {} is clickable", case.name, stop.key.elem);
            }
        }
    }
}

